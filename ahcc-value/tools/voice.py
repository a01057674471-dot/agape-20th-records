# Narration: the user's recording (voices/source.mp3, 32.4 s) cut at its 18 pauses (one per phrase of the script),
# sped up 1.12× (pitch kept) and laid card by card; each card starts on an eighth note of the 120 bpm grid.
# → voices/narration.wav and voices/times.js (the timeline film.js reads)
# run: python3 tools/voice.py
import os, subprocess, json, math, numpy as np, wave
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, 'voices', 'source.mp3'); SR = 48000; SPEED = 1.12; E8 = .25
P = [  # (card, id, source start, source end, text)
  ('hook', 'v01', 0.16, 0.98, '면역 제품,'), ('hook', 'v02', 1.19, 2.13, '뭘 보고 고르세요?'),
  ('three', 'v03', 2.51, 3.79, '딱 3가지만 확인하세요.'),
  ('c1', 'v04', 4.22, 4.64, '첫째,'), ('c1', 'v05', 4.80, 6.49, '식약처가 인정한 기능성인가.'), ('c1', 'v06', 6.95, 9.37, '라파힐 AHCC는 식약처 개별인정,'), ('c1', 'v07', 9.61, 11.47, '면역기능 증진에 도움을 줄 수 있습니다.'),
  ('c2', 'v08', 11.93, 12.30, '둘째,'), ('c2', 'v09', 12.48, 13.69, '사람에게서 확인됐는가.'), ('c2', 'v10', 14.14, 17.91, '인체시험으로 수지상세포 증가와 NK세포 활성을 확인했습니다.'),
  ('c3', 'v11', 18.35, 18.78, '셋째,'), ('c3', 'v12', 19.00, 20.38, '오래 검증된 원료인가.'), ('c3', 'v13', 20.75, 22.19, '오래된 데는 이유가 있습니다.'), ('c3', 'v14', 22.57, 25.26, '1980년대부터 30년 넘게 이어진 연구.'),
  ('verdict', 'v15', 25.64, 26.39, '3가지 모두,'), ('verdict', 'v16', 26.62, 27.95, '라파힐 AHCC.'),
  ('end', 'v17', 28.40, 30.13, '면역의 기본, 근거로 고르세요.'), ('end', 'v18', 30.56, 32.40, '지금 프로필 링크에서 만나보세요.'),
]
def clip(a, b):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-ss', str(max(0, a - .03)), '-to', str(b + .05), '-i', SRC, '-af', f'atempo={SPEED}', '-ac', '1', '-ar', str(SR), '-f', 's16le', '-'], capture_output=True, check=True).stdout
    x = np.frombuffer(raw, np.int16).astype(np.float32) / 32768; k = int(.008 * SR); x[:k] *= np.linspace(0, 1, k); x[-k:] *= np.linspace(1, 0, k); return x
MIN = {'hook': 2.5, 'three': 2.25, 'verdict': 2.75}      # cards whose lines need more reading time than their speech
lay, cards, t, prev = [], {}, 0.0, None
for card, pid, a, b, text in P:
    x = clip(a, b)
    if card != prev:
        if prev is not None: t = max(t, cards[prev] + MIN.get(prev, 0))
        c0 = 0.0 if prev is None else math.ceil((t + .02) / E8 - 1e-9) * E8
        cards[card] = round(c0, 3); t = c0 + .05; prev = card
    else:
        t += .04 if lay[-1][4].endswith(',') else .1
    lay.append((pid, t, x, card, text)); t += len(x) / SR
dur = max(30.0, round(math.ceil((t + .4) / E8) * E8, 3))
out = np.zeros(int(dur * SR), np.float32)
for pid, t0, x, _, _ in lay: i = int(t0 * SR); out[i:i + len(x)] += x[:len(out) - i]
with wave.open(os.path.join(HERE, 'voices', 'narration.wav'), 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(out, -1, 1) * 32767).astype(np.int16).tobytes())
V = {pid: [round(t0, 3), round(t0 + len(x) / SR, 3), text] for pid, t0, x, _, text in lay}
open(os.path.join(HERE, 'voices', 'times.js'), 'w', encoding='utf-8').write('// generated by tools/voice.py — the narration timeline (seconds)\nexport const DUR = %s;\nexport const CARD_T0 = %s;\nexport const V = %s;\n' % (dur, json.dumps(cards), json.dumps(V, ensure_ascii=False, indent=1)))
print('narration', dur, 's;', ', '.join(f'{k} {v:.2f}' for k, v in cards.items()))
