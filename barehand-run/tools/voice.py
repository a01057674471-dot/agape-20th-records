# Narration: cut the user's recording (voices/source.mp3, 62.6 s) at its pauses, keep the core phrases, speed each one up 1.5×
# (pitch kept, ffmpeg atempo) and lay them on the film's timeline. Each card starts on an eighth note of the 150 bpm grid.
# Phrase boundaries come from the recording's pauses (silencedetect), matched one-to-one to the 30 phrases of the script.
# → voices/narration.wav and voices/times.js (the timeline film.js reads)
# run: python3 tools/voice.py
import os, subprocess, json, math, numpy as np, wave
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, 'voices', 'source.mp3'); SR = 48000; SPEED = 1.5; E8 = .2
# (card, id, source start, source end, text)
P = [
  ('hook',   'v01', 0.19, 1.56, '만약 겨울 내내,'), ('hook', 'v02', 1.85, 4.00, '영하에서 맨손으로 달린다면?'),
  ('wind',   'v04', 6.25, 9.75, '영하 10도에 6분 페이스면 손은 영하 15도.'),
  ('wind',   'v08', 16.29, 17.94, '영하 27도부터는'), ('wind', 'v09', 18.29, 20.54, '동상 위험이 급격히 커집니다.'),
  ('finger', 'v10', 20.99, 22.95, '손가락이 15도까지 식으면,'), ('finger', 'v11', 23.25, 25.30, '손놀림이 급격히 떨어집니다.'),
  ('study',  'v12', 25.75, 28.29, '그럼 겨울 내내 하면 손이 적응할까요?'), ('study', 'v13', 28.69, 31.56, '16명이 8도 물에 하루 30분,'), ('study', 'v14', 31.94, 34.07, '15번 손을 담갔습니다.'),
  ('result', 'v16', 35.44, 36.71, '통증은 줄었지만'), ('result', 'v18', 39.53, 41.06, '스스로 데워지는 반응은'), ('result', 'v19', 41.34, 42.72, '52%에서'), ('result', 'v20', 43.04, 45.06, '24%로 줄었습니다.'),
  ('twist',  'v22', 47.35, 49.39, '덜 아픈 건 적응이 아니라,'), ('twist', 'v23', 49.68, 50.66, '둔해진 겁니다.'),
  ('check',  'v24', 51.11, 53.29, '체감 영하 27도 아래라면'), ('check', 'v25', 53.57, 54.71, '장갑은 필수.'),
  ('cta',    'v28', 58.17, 59.71, '당신은 장갑파인가요,'), ('cta', 'v29', 59.95, 61.01, '맨손파인가요?'), ('cta', 'v30', 61.29, 62.56, '댓글로 알려주세요.'),
]
def clip(a, b):
    a, b = max(0, a - .04), b + .06
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-ss', str(a), '-to', str(b), '-i', SRC, '-af', f'atempo={SPEED}', '-ac', '1', '-ar', str(SR), '-f', 's16le', '-'], capture_output=True, check=True).stdout
    x = np.frombuffer(raw, np.int16).astype(np.float32) / 32768
    k = int(.008 * SR); x[:k] *= np.linspace(0, 1, k); x[-k:] *= np.linspace(1, 0, k)
    return x
lay, cards, t, prev = [], {}, 0.0, None
for card, pid, a, b, text in P:
    x = clip(a, b)
    if card != prev:                                    # a new card: next eighth note after a short breath; the voice enters one sixteenth later
        c0 = 0.0 if prev is None else math.ceil((t + (.24 if card == 'twist' else .04)) / E8 - 1e-9) * E8   # the twist gets its half beat of silence
        cards[card] = round(c0, 3); t = c0 + (.06 if prev is None else .05); prev = card
    else:
        t += .03 if not lay[-1][4].endswith(('.', '?')) else .07
    lay.append((pid, t, x, card, text)); t += len(x) / SR
dur = round(math.ceil((t + .6) / E8) * E8, 3)
out = np.zeros(int(dur * SR) + SR, np.float32)
for pid, t0, x, _, _ in lay: i = int(t0 * SR); out[i:i + len(x)] += x
out = out[:int(dur * SR)]
with wave.open(os.path.join(HERE, 'voices', 'narration.wav'), 'wb') as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(out, -1, 1) * 32767).astype(np.int16).tobytes())
V = {pid: [round(t0, 3), round(t0 + len(x) / SR, 3), text] for pid, t0, x, _, text in lay}
js = '// generated by tools/voice.py — the narration timeline (seconds)\nexport const DUR = %s;\nexport const CARD_T0 = %s;\nexport const V = %s;\n' % (round(dur, 3), json.dumps(cards), json.dumps(V, ensure_ascii=False, indent=1))
open(os.path.join(HERE, 'voices', 'times.js'), 'w', encoding='utf-8').write(js)
print('narration', round(dur, 2), 's;', ', '.join(f'{k} {v:.1f}' for k, v in cards.items()))
