# The film's clock. Until the narration is recorded, each line's length is estimated from its syllables
# (4.6 syllables/s, a digit counts as a syllable) with a breath after it and a longer hold between chapters,
# so the chart has room to be watched. When voices/times.json exists (line → [start, end] in the recording),
# its real lengths are used instead. → voices/times.js
# run: python3 tools/timeline.py
import os, json, re
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = json.load(open(os.path.join(HERE, 'lines.json'), encoding='utf-8'))
rec = os.path.join(HERE, 'voices', 'times.json')
R = json.load(open(rec)) if os.path.exists(rec) else None
RATE, BREATH, HOLD = 4.6, .7, 3.0
t, prev, V, SCN = 1.0, None, {}, {}
for l in L:
    if l['scene'] != prev:
        if prev is not None: t += HOLD
        SCN[l['scene']] = round(t - .5, 3); prev = l['scene']
    if R and l['id'] in R: d = R[l['id']][1] - R[l['id']][0]
    else: d = (len(re.findall(r'[가-힣]', l['text'])) + len(re.findall(r'[0-9]', l['text'])) + .5 * len(re.findall(r'[A-Za-z]', l['text']))) / RATE
    V[l['id']] = [round(t, 3), round(t + d, 3), l['text']]; t += d + BREATH
DUR = round(t + 2.5, 2)
open(os.path.join(HERE, 'voices', 'times.js'), 'w', encoding='utf-8').write(
  '// generated by tools/timeline.py — %s\nexport const DUR = %s;\nexport const SCENE_T0 = %s;\nexport const V = %s;\n' % ('from the recording' if R else 'estimated, no recording yet', DUR, json.dumps(SCN), json.dumps(V, ensure_ascii=False, indent=1)))
print('timeline', DUR, 's (%d:%02d)' % (DUR // 60, DUR % 60), '|', ', '.join(f'{k} {v:.1f}' for k, v in SCN.items()))
